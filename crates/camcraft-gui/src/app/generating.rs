//! Where generating stands, said where a person looks: under the selected
//! operation's settings, and over the setup's view.
//!
//! Generating is the app's own business, started as soon as editing settles
//! ([`crate::document::Document::wanting_runs`]), so what is said here is what
//! it is doing and how far it has got, and the one thing to do about it: stop
//! it, or have it generate again once stopped or failed.

use eframe::egui;

use crate::browser::{running_text, work_text};
use crate::document::{Document, Halt, OpStatus, Status};
use crate::ui::widgets::{self, hint_text};

/// What the footer asks for.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum Asked {
    /// Stop generating the setup.
    Stop,
    /// Generate the setup again, as it stands.
    Generate,
}

/// Where operation `index` of setup `setup` of `doc` stands, in a line under
/// its settings, and a button for what can be done about it. `auto` is
/// whether setups are generated by themselves.
pub(super) fn footer(
    ui: &mut egui::Ui,
    doc: &Document,
    (setup, index): (&str, usize),
    auto: bool,
) -> Option<Asked> {
    let status = doc
        .op_statuses(setup)
        .get(index)
        .copied()
        .unwrap_or(OpStatus::NotRun);
    let whole = doc.status(setup);
    let failed = doc
        .setups
        .get(setup)
        .and_then(|s| s.halted.as_ref())
        .and_then(|(_, h)| match h {
            Halt::Failed { why, .. } => Some(why.clone()),
            Halt::Stopped => None,
        });
    let mut asked = None;
    ui.horizontal(|ui| {
        let (text, detail, button): (String, Option<String>, Option<(&str, Asked)>) = match status {
            OpStatus::Running { since, work, done } => {
                widgets::status_gauge(ui, widgets::Level::Ok.color(), done);
                (
                    "Generating".into(),
                    Some(format!(
                        "{}, {}",
                        work_text(work),
                        running_text(done, since)
                    )),
                    Some(("Stop", Asked::Stop)),
                )
            }
            OpStatus::Waiting => {
                ui.spinner();
                (
                    "Waiting".into(),
                    Some("for the operations before it, whose material it cuts".into()),
                    Some(("Stop", Asked::Stop)),
                )
            }
            OpStatus::Done | OpStatus::Warnings => {
                let with = if status == OpStatus::Warnings {
                    ", with warnings"
                } else {
                    ""
                };
                let rest = (whole == Status::Running)
                    .then(|| "the operations after it are still generating".to_string());
                (
                    format!("Generated{with}"),
                    rest,
                    (whole == Status::Running).then_some(("Stop", Asked::Stop)),
                )
            }
            OpStatus::Failed => (
                "Generating it failed".into(),
                failed.clone(),
                Some(("Try again", Asked::Generate)),
            ),
            OpStatus::Disabled => ("Turned off".into(), Some("not generated".into()), None),
            OpStatus::Stale | OpStatus::NotRun => match (whole, doc.cannot_generate(setup, None)) {
                (Status::Stopped, _) => (
                    "Stopped".into(),
                    Some("it generates again once it changes".into()),
                    Some(("Generate", Asked::Generate)),
                ),
                (Status::Failed, _) => (
                    "Not generated".into(),
                    Some("an operation before it failed".into()),
                    Some(("Try again", Asked::Generate)),
                ),
                (_, Some(why)) => ("Not generated yet".into(), Some(why), None),
                (_, None) if auto => (
                    if status == OpStatus::Stale {
                        "Out of date".into()
                    } else {
                        "Not generated".into()
                    },
                    Some("it generates as soon as editing settles".into()),
                    None,
                ),
                (_, None) => (
                    "Not generated".into(),
                    None,
                    Some(("Generate", Asked::Generate)),
                ),
            },
        };
        ui.vertical(|ui| {
            ui.label(egui::RichText::new(text).strong());
            if let Some(detail) = detail {
                ui.label(hint_text(detail));
            }
        });
        if let Some((label, what)) = button {
            ui.with_layout(egui::Layout::right_to_left(egui::Align::Center), |ui| {
                let icon = match what {
                    Asked::Stop => widgets::Icon::Square,
                    Asked::Generate => widgets::Icon::Play,
                };
                if widgets::button(
                    ui,
                    widgets::Variant::Secondary,
                    widgets::Size::Md,
                    Some(icon),
                    label,
                )
                .clicked()
                {
                    asked = Some(what);
                }
            });
        }
    });
    asked
}

/// Over the setup's view, what is drawn of a run that is not all there is:
/// one still generating, shown as far as it has got, or one made before the
/// setup changed.
pub(super) fn banner(ui: &mut egui::Ui, status: Status, share: Option<f64>) {
    let text = match status {
        Status::Running => match share {
            Some(share) => format!("Generating: {:.0}%.", share * 100.0),
            None => "Generating: laying out the part and stock.".into(),
        },
        Status::Stale => {
            "Out of date: what shows was made before the setup changed. It generates again \
             as soon as editing settles."
                .into()
        }
        Status::Stopped => {
            "Stopped: what shows is as far as it got. It generates again once it changes.".into()
        }
        Status::Failed => {
            "Generating it failed: what shows is as far as it got. See the log.".into()
        }
        Status::NotRun | Status::Verified | Status::Warnings | Status::Refused => return,
    };
    // Under way is no finding: said quietly, beside a spinner.
    if status == Status::Running {
        ui.horizontal_wrapped(|ui| {
            ui.spinner();
            ui.label(hint_text(text));
        });
    } else {
        let level = match status {
            Status::Failed => widgets::Level::Err,
            _ => widgets::Level::Warn,
        };
        widgets::diagnostic(ui, level, &text, |_| {});
    }
    ui.add_space(6.0);
}
