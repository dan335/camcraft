/// The Masso profile written plainly: every digit, no line numbers, so the
/// tests read the renderer's decisions rather than its dialect.
fn masso() -> Profile {
    let mut p = Profile::builtin("masso").unwrap().unwrap();
    p.format.strip_trailing_zeros = false;
    p.numbering.enabled = false;
    p
}

/// The Masso profile as it is shipped writes as Fusion's Masso post does:
/// blocks numbered in fives from N10, comments not, and numbers without
/// their trailing zeros but with their point.
#[test]
fn masso_writes_as_fusions_post_does() {
    let p = Profile::builtin("masso").unwrap().unwrap();
    let g = program(&p);
    let lines: Vec<&str> = g.lines().collect();
    assert_eq!(lines[0], "(test)", "{g}");
    assert_eq!(lines[2], "N10 G90 G94 G17", "{g}");
    assert_eq!(lines[3], "N15 G21", "{g}");
    assert!(g.contains("G0 X0. Y0."), "{g}");
    assert!(g.contains(" Z10.\n"), "{g}");
    assert!(g.contains("X10. F1200."), "{g}");
    assert!(
        lines
            .iter()
            .filter(|l| l.starts_with('('))
            .all(|l| !l.contains('N')),
        "{g}"
    );
}

/// The Avid profile writes as Fusion's Avid CNC post does: across after the
/// change, then down taking up the tool's length offset; Z home before the
/// change and at the end, then over the work origin.
#[test]
fn centroid_avid_writes_as_fusions_avid_post_does() {
    let p = Profile::builtin("centroid-avid").unwrap().unwrap();
    let g = program(&p);
    let lines: Vec<&str> = g.lines().collect();
    assert_eq!(
        lines.get(..4),
        Some(
            &[
                "(TEST)",
                "(GENERATED BY CAMCRAFT -- VERIFY BEFORE RUNNING)",
                "G90 G94 G40 G49 G17",
                "G21",
            ][..]
        ),
        "{g}"
    );
    let change = lines.iter().position(|l| *l == "T1 M6").unwrap();
    assert_eq!(lines.get(change - 1), Some(&"G53 G0 Z0"), "{g}");
    assert_eq!(
        lines.get(change + 1..change + 5),
        Some(&["G54", "S18000 M3", "G0 X0 Y0", "G43 Z10 H1"][..]),
        "{g}"
    );
    assert!(g.contains("\nG1 Z0 F300\nX10 F1200\n"), "{g}");
    assert_eq!(g.matches("G43").count(), 1, "{g}");
    let tail: Vec<&str> = lines.iter().rev().take(4).copied().collect();
    assert_eq!(tail, ["M30", "G0 X0 Y0", "G53 G0 Z0", "M5"], "{g}");
}

/// Without a safe retract, the length offset is taken up with the first move,
/// which is the one down (or up) to the crossing height; whatever the first
/// move is, it is taken up once. Profiles that do not ask for it never get it.
#[test]
fn a_length_offset_rides_on_the_first_z() {
    let mut p = Profile::builtin("centroid-avid").unwrap().unwrap();
    p.safe_retract.clear();
    let g = program(&p);
    let first = g.lines().position(|l| l.starts_with("G0")).unwrap();
    assert_eq!(
        g.lines().skip(first).take(2).collect::<Vec<_>>(),
        ["G0 G43 Z10 H1", "X0 Y0"],
        "{g}"
    );

    let mut t = Toolpath::new();
    t.feed_to(dvec3(1.0, 2.0, 3.0), MoveRole::Plunge, 300.0)
        .unwrap();
    t.feed_to(dvec3(1.0, 2.0, 0.0), MoveRole::Plunge, 300.0)
        .unwrap();
    let ops = crate::op::lower(&t, &ProgramSpec::default()).unwrap();
    let (g, _) = render(&ops, &p, "t");
    assert!(g.contains("\nG1 G43 X1 Y2 Z3 H1 F300\nZ0\n"), "{g}");

    assert!(!program(&masso()).contains("G43"));
}

/// In inches, every length and feed is converted, and the program says G20.
#[test]
fn inches_convert_every_length_and_feed() {
    let p = Profile::builtin("masso-inch").unwrap().unwrap();
    let spec = ProgramSpec {
        units: ProgramUnits::Inch,
        ..ProgramSpec::default()
    };
    let mut t = Toolpath::new();
    t.rapid_to(dvec3(25.4, 50.8, 12.7)).unwrap();
    t.feed_to(dvec3(25.4, 50.8, 0.0), MoveRole::Plunge, 254.0)
        .unwrap();
    t.arc_to(
        dvec3(25.4 + 12.7, 50.8 + 12.7, 0.0),
        Arc {
            centre: dvec3(25.4, 50.8 + 12.7, 0.0),
            axis: DVec3::Z,
            sweep: FRAC_PI_2,
        },
        MoveRole::Cut,
        3810.0,
    )
    .unwrap();
    let ops = crate::op::lower(&t, &spec).unwrap();
    let (g, _) = render(&ops, &p, "t");
    assert!(g.contains(" G20\n"), "{g}");
    assert!(g.contains("G0 X1. Y2."), "{g}");
    assert!(g.contains("G1 Z0. F10."), "{g}");
    assert!(g.contains("G3 X1.5 Y2.5 I0. J0.5 F150."), "{g}");
}

fn path() -> Toolpath {
    let mut t = Toolpath::new();
    t.rapid_to(dvec3(0.0, 0.0, 10.0)).unwrap();
    t.feed_to(dvec3(0.0, 0.0, 0.0), MoveRole::Plunge, 300.0)
        .unwrap();
    t.feed_to(dvec3(10.0, 0.0, 0.0), MoveRole::Cut, 1200.0)
        .unwrap();
    t.feed_to(dvec3(10.0, 5.0, 0.0), MoveRole::Cut, 1200.0)
        .unwrap();
    t
}

fn program(p: &Profile) -> String {
    let ops = crate::op::lower(&path(), &ProgramSpec::default()).unwrap();
    render(&ops, p, "test").0
}

